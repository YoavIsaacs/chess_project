/**
  * @brief  USART1 global interrupt handler.
  *
  *         USART1_RxISR() (defined in main.c) runs first — it reads SR and DR
  *         directly, accumulating bytes into the volatile RX line buffer and
  *         setting s_uart_rx_line_ready on '\n'.  Because the ISR consumes
  *         RXNE and clears ORE before HAL_UART_IRQHandler runs, the HAL
  *         handler finds no pending flags and exits immediately, so it does
  *         not interfere with the raw-register RX path.
  */
void USART1_IRQHandler(void)
{
  /* USER CODE BEGIN USART1_IRQn 0 */
  USART1_RxISR();
  /* USER CODE END USART1_IRQn 0 */
  HAL_UART_IRQHandler(&huart1);
  /* USER CODE BEGIN USART1_IRQn 1 */
  /* USER CODE END USART1_IRQn 1 */
}

